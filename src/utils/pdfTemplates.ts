// Generates an offscreen clean white canvas thumbnail
export const generateBlankPageDataUrl = (width: number, height: number, pageNum: number): string => {
  if (typeof document === 'undefined') return '';
  const canvas = document.createElement('canvas');
  // Scale down for crisp thumbnail
  canvas.width = Math.round(width * 0.5);
  canvas.height = Math.round(height * 0.5);
  const ctx = canvas.getContext('2d');
  if (ctx) {
    ctx.fillStyle = '#ffffff';
    ctx.fillRect(0, 0, canvas.width, canvas.height);

    // Subtle page border
    ctx.strokeStyle = '#e2e8f0';
    ctx.lineWidth = 1;
    ctx.strokeRect(0, 0, canvas.width, canvas.height);

    // Subtle page number watermark
    ctx.fillStyle = '#cbd5e1';
    ctx.font = '12px sans-serif';
    ctx.textAlign = 'center';
    ctx.fillText(`${pageNum}`, canvas.width / 2, canvas.height - 12);
  }
  return canvas.toDataURL('image/png');
};

