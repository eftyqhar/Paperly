// Creates a complete new PDF document state
export const createNewPdfDocument = (
  options: CreatePdfOptions
): { pages: PdfPageInfo[]; elements: CanvasElement[] } => {
  const baseDim = PAGE_SIZES[options.pageSize] || PAGE_SIZES.a4;
  const isLandscape = options.orientation === 'landscape';
  const width = isLandscape ? Math.max(baseDim.width, baseDim.height) : Math.min(baseDim.width, baseDim.height);
  const height = isLandscape ? Math.min(baseDim.width, baseDim.height) : Math.max(baseDim.width, baseDim.height);

  const pages: PdfPageInfo[] = [];
  const count = Math.max(1, Math.min(50, options.pageCount || 1));

  for (let i = 1; i <= count; i++) {
    pages.push({
      pageNumber: i,
      width,
      height,
      rotation: 0,
      renderedImageUrl: generateBlankPageDataUrl(width, height, i),
      textBlocks: [],
    });
  }

  const elements = getTemplateElements(options.templateId, width, height);

  return { pages, elements };
};
